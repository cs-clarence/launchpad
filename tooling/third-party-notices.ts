// Writes THIRD_PARTY_NOTICES.md: the name, version and declared licence of every third-party
// package in the runtime dependency closure of the controller, worker and router, read from the
// installed packages (so run `bun install --frozen-lockfile` first). It lists what the manifests
// declare; it does not reproduce licence texts and is not legal advice.
//   bun tooling/third-party-notices.ts          rewrite the file
//   bun tooling/third-party-notices.ts --check  fail if the file is out of date
import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const OUTPUT = path.join(root, "THIRD_PARTY_NOTICES.md");
const APPS = ["controller", "worker", "router"];

// devDependencies of the controller whose files still end up in its image: the build copies or
// inlines them (verified in apps/controller/.output: Scalar's bundle under public/_scalar, the
// Skeleton and Tailwind CSS in the stylesheet, Nitro's runtime in server/). Only these; the other
// dev tools (vite, typescript, vitest, the React plugin, type packages) are not shipped.
export const SHIPPED_DEV_ROOTS: Record<string, string[]> = {
    controller: [
        "@scalar/api-reference",
        "@skeletonlabs/skeleton",
        "@skeletonlabs/skeleton-react",
        "nitro",
        "tailwindcss",
    ],
};

type Manifest = {
    name: string;
    version: string;
    license?: string | { type?: string };
    licenses?: Array<{ type?: string }>;
    dependencies?: Record<string, string>;
    optionalDependencies?: Record<string, string>;
};

const read = (dir: string): Manifest =>
    JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));

function resolveFrom(dir: string, name: string): string | undefined {
    for (let current = dir; ; current = path.dirname(current)) {
        const candidate = path.join(current, "node_modules", name);
        if (existsSync(path.join(candidate, "package.json"))) return realpathSync(candidate);
        if (path.dirname(current) === current) return undefined;
    }
}

function licenceOf(manifest: Manifest): string {
    const { license, licenses } = manifest;
    if (typeof license === "string") return license;
    if (license?.type) return license.type;
    const listed = licenses?.map((entry) => entry.type).filter(Boolean);
    return listed?.length ? listed.join(" OR ") : "UNDECLARED";
}

export function collect(): Array<{ name: string; version: string; license: string }> {
    const seen = new Map<string, { name: string; version: string; license: string }>();
    const visited = new Set<string>();
    const walk = (dir: string) => {
        if (visited.has(dir)) return;
        visited.add(dir);
        const manifest = read(dir);
        if (!manifest.name.startsWith("@launchpad-kit/")) {
            seen.set(`${manifest.name}@${manifest.version}`, {
                name: manifest.name,
                version: manifest.version,
                license: licenceOf(manifest),
            });
        }
        for (const name of Object.keys(manifest.dependencies ?? {})) {
            const found = resolveFrom(dir, name);
            if (!found) throw new Error(`${name} (needed by ${manifest.name}) is not installed`);
            walk(found);
        }
    };
    for (const app of APPS) walk(path.join(root, "apps", app));
    for (const [app, names] of Object.entries(SHIPPED_DEV_ROOTS)) {
        const appDir = path.join(root, "apps", app);
        for (const name of names) {
            const found = resolveFrom(appDir, name);
            if (!found) throw new Error(`${name} (shipped by ${app}) is not installed`);
            walk(found);
        }
    }
    return [...seen.values()].sort(
        (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
    );
}

export function render(packages = collect()): string {
    const counts = new Map<string, number>();
    for (const entry of packages) counts.set(entry.license, (counts.get(entry.license) ?? 0) + 1);
    const summary = [...counts].sort((a, b) => b[1] - a[1]).map(([id, n]) => `| ${id} | ${n} |`);
    return `# Third-party notices

Launchpad is licensed under the Apache License 2.0 (\`LICENSE\`). The images also contain software
from other projects under their own licences. This file is generated by
\`bun tooling/third-party-notices.ts\` from the packages installed for the controller, worker and
router (their runtime dependency closure plus the controller's build-time packages whose files are shipped in the image, read from the packages installed by \`bun install --frozen-lockfile\`); it lists the licence each
package **declares** in its \`package.json\` and does not reproduce licence texts. The packages'
own files hold the full terms. For the build-time packages the full dependency closure is listed, which can include more than the shipped bundle contains. Optional dependencies (platform-specific binaries) are not followed, so the file is the same on every platform.

## Runtime and base image

- **Bun** (the \`oven/bun\` images). Bun is MIT licensed and statically links
  JavaScriptCore, which is LGPL-2 licensed (WebKit), along with other components. See
  <https://bun.sh/docs/project/licensing> for the exact terms and the list of bundled software.
- **Debian** (the base of the \`-slim\` Bun images and of the packages \`apt\` installs, such as
  \`openssh-client\` and, in the admin image, \`postgresql-client-17\`). Debian packages carry their
  own licences, in \`/usr/share/doc/<package>/copyright\` inside the image.
- **Docker CLI** (the worker image copies the \`docker\` binary from \`docker:cli\`): Apache-2.0.
- **Dokku** (the \`launchpad-dokku\` image builds on \`dokku/dokku\`, MIT, on an Ubuntu base) and the
  \`dokku-http-auth\` plugin it installs from the pinned commit. Their licences are those of
  the upstream projects and of the distribution packages in the image.

## npm packages by declared licence

| Licence | Packages |
| ------- | -------- |
${summary.join("\n")}

## npm packages

| Package | Version | Declared licence |
| ------- | ------- | ---------------- |
${packages.map((entry) => `| ${entry.name} | ${entry.version} | ${entry.license} |`).join("\n")}
`;
}

/** Whether the file at `file` differs from `expected` (a missing file counts as stale). */
export function isStale(file: string, expected: string): boolean {
    return !existsSync(file) || readFileSync(file, "utf8") !== expected;
}

if (import.meta.main) {
    const flag = process.argv.indexOf("--output");
    const output = flag > 0 ? path.resolve(process.argv[flag + 1]!) : OUTPUT;
    const text = render();
    if (process.argv.includes("--check")) {
        if (isStale(output, text)) {
            console.error(
                "THIRD_PARTY_NOTICES.md is out of date: run bun tooling/third-party-notices.ts",
            );
            process.exit(1);
        }
    } else {
        writeFileSync(output, text);
    }
}
